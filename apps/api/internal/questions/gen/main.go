// Command gen regenerates figures_gen.go from packages/figures/figures.json.
//
// That JSON file is the single source of truth for the approved question-figure
// vocabulary; the web client (apps/web/src/lib/figures.ts) and the Python
// pipeline (services/content-pipeline) read the same file. Run it with
// `go generate ./internal/questions/...` from apps/api.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

type figure struct {
	Name  string `json:"name"`
	Label string `json:"label"`
	Color string `json:"color"`
}

// figuresJSON is the path from this package directory (the cwd of `go generate`)
// to the shared vocabulary at the repository root.
const figuresJSON = "../../../../packages/figures/figures.json"

func main() {
	raw, err := os.ReadFile(figuresJSON)
	if err != nil {
		fmt.Fprintln(os.Stderr, "read figures.json:", err)
		os.Exit(1)
	}
	var figures []figure
	if err := json.Unmarshal(raw, &figures); err != nil {
		fmt.Fprintln(os.Stderr, "parse figures.json:", err)
		os.Exit(1)
	}
	if len(figures) == 0 {
		fmt.Fprintln(os.Stderr, "figures.json is empty")
		os.Exit(1)
	}
	for _, f := range figures {
		if f.Name == "" || f.Label == "" || f.Color == "" {
			fmt.Fprintf(os.Stderr, "incomplete entry: %+v\n", f)
			os.Exit(1)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	buf.WriteString("// Source: packages/figures/figures.json\n\n")
	buf.WriteString("package questions\n\n")
	buf.WriteString("// Icons is the approved set of question figures, generated from\n")
	buf.WriteString("// packages/figures/figures.json — the single source of truth shared with the\n")
	buf.WriteString("// web client and the Python pipeline.\n")
	buf.WriteString("var Icons = []string{\n")
	for _, f := range figures {
		fmt.Fprintf(&buf, "\t%s,\n", strconv.Quote(f.Name))
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "format:", err)
		os.Exit(1)
	}
	out := filepath.Join(".", "figures_gen.go")
	if err := os.WriteFile(out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d icons)\n", out, len(figures))
}
